<h1 id="why-plain-text">Why plain text?</h1>
<p>
    Primary sources are the bricks of a historical argument. Quoting them well takes sensitivity
    and attention to context, so historians have to go back to their sources often, and be able to
    search them quickly (with Ctrl+F). History is also a collective enterprise: historians should be
    able to send a source to a colleague and ask for help in interpreting it.
</p>
<p>
    All of this is very difficult when a source is only available as a grainy scan or image. This
    site aims to fix that, one source at a time. We chose plain
    text because it is an open, portable file format that is likely to survive many decades into the
    future, unlike proprietary formats such as .docx.<?= sn('Technically we use Markdown rather than plain text, but Markdown is plain text with a few light conventions for headings and emphasis, and it reads fine as it is.') ?>
</p>

<h1 id="someone-elses-job">Isn't this someone else's job?</h1>
<p>
    Why should a historian deal with transcription and hosting? Isn't this the job of publishers?
</p>
<p>
    This site does not try to compete with the large newspaper archives on the number of sources.
    It aims for quality instead: every transcription is checked by hand against the original, and
    every article comes with an accurate citation. The person best placed to do this work is
    precisely the historian who is using these sources in their own research.
</p>

<h1 id="copyright">Is this copyright infringement?</h1>
<p>
    No. We only transcribe texts that are in the public domain.
</p>

<h1 id="why-did-you-make-old-text">Why did you make Plain Old Text?</h1>
<p>The project began, under the name Old News, out of frustration while
    reading a history of 19th-century science that leans heavily on
    newspaper articles but leaves the reader to hunt down the original pages
    on platforms like The British Newspaper Archive. Since the texts are in
    the public domain, it seemed a small effort to transcribe them and host
    them somewhere easy to read and reference. The archive has grown since
    then, and so has its scope, hence the new name.</p>

